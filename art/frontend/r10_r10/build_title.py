#!/usr/bin/env python3
"""Compile the approved arcade-raster PANG adaptation for moving and settled art.

Only horizontal geometry changes (384->320, 5/6).  Vertical pixels, bevels,
counters and the original actor timing remain 1:1.  The source PNG contains the
approved final 320x80 PANG band; it is indexed back to the original four palette
banks and sliced on the original animation-cell boundaries.
"""
from pathlib import Path
import hashlib,json,re
import numpy as np
from PIL import Image
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
source=json.loads((HERE/'title_source.json').read_text())
stage=(ROOT/'stage/stage_data.c').read_text()
def array(name):
    body=re.search(r'const uint8_t '+name+r'\[\d+\]=\{(.*?)\};',stage,re.S).group(1)
    return bytes(int(v,16) for v in re.findall(r'0x([0-9a-fA-F]{2})',body))
bank=array('hk_bank3');rb=lambda a:bank[a-0x8000];rw=lambda a:rb(a)+(rb(a+1)<<8)
project=lambda x:x*5//6
# Per-letter original palette pens (RGB444). Pen0 stays transparent.
palettes=[[0xfff,0xabf,0xadf,0x7cf,0x4bf,0x1af,0x19f,0x18f,0x17e,0x16d],
          [0xfff,0xadd,0xadf,0x7cf,0x4bf,0x1af,0x19f,0x18f,0x17e,0x16d],
          [0xfff,0xcbd,0xadf,0x7cf,0x4bf,0x1af,0x19f,0x18f,0x17e,0x16d],
          [0xfff,0xdcc,0xadf,0x7cf,0x4bf,0x1af,0x19f,0x18f,0x17e,0x16d]]
def rgb444(v):return ((v>>8)&15,(v>>4)&15,v&15)
palette_maps=[{rgb444(v):i+1 for i,v in enumerate(p)} for p in palettes]
# The retained source is an actual renderer capture; reduce each channel back
# to its exact RGB444 identity before assigning pens.
raster=np.asarray(Image.open(HERE.parent/'r10_r14/pang_arcade_adapted.png').convert('RGB'))
assert raster.shape==(80,320,3),raster.shape
q=np.rint(raster/17).astype(np.uint8)
bg=(0,0,9);shadow=(1,1,4)
main=np.logical_and(np.any(q!=bg,axis=2),np.any(q!=shadow,axis=2))
# Connected components preserve overlapping P/A bounds without inventing a
# vertical cut. The four largest components are the four letters; detached
# highlight pixels are assigned to the nearest letter centre.
seen=np.zeros(main.shape,bool);components=[]
for y in range(80):
 for x in range(320):
  if not main[y,x] or seen[y,x]:continue
  stack=[(x,y)];seen[y,x]=1;points=[]
  while stack:
   px,py=stack.pop();points.append((px,py))
   for dy in (-1,0,1):
    for dx in (-1,0,1):
     if not (dx or dy):continue
     nx,ny=px+dx,py+dy
     if 0<=nx<320 and 0<=ny<80 and main[ny,nx] and not seen[ny,nx]:
      seen[ny,nx]=1;stack.append((nx,ny))
  components.append(points)
major=sorted(components,key=len,reverse=True)[:4]
major=sorted(major,key=lambda c:sum(x for x,_ in c)/len(c))
centres=[sum(x for x,_ in c)/len(c) for c in major]
letters=[np.zeros((240,320),np.uint8) for _ in range(4)]
for component in components:
 cx=sum(x for x,_ in component)/len(component)
 letter=min(range(4),key=lambda i:abs(cx-centres[i]))
 mapping=palette_maps[letter]
 for x,y in component:
  color=tuple(int(v) for v in q[y,x])
  assert color in mapping,(letter,x,y,color)
  letters[letter][112+y,x]=mapping[color]
assert [int(np.count_nonzero(p)) for p in letters]==[3452,3869,4602,3676], [int(np.count_nonzero(p)) for p in letters]
records=[];slices={};conflicts=[];coverage=[]
for letter,item in enumerate(source['letters']):
    front=item['anchor'];covered=np.zeros((240,320),bool)
    for shadow_variant in (0,1):
        variant=letter*4+shadow_variant*2;shape=rw(0xacdb+variant);motion=rw(0xabf3+variant)
        anchor=(rw(motion+24),rb(motion+26));dx=dy=0;n=rb(shape+1);delta=rw(shape+2)
        shift=(project(anchor[0]-64)-project(front[0]-64),(anchor[1]-8)-(front[1]-8))
        for i in range(n):
            at=rb(shape+5+i*2);code=rb(shape+4+i*2)+((at&224)<<3)
            d=rb(delta+i*2);dx+=d-256 if d&128 else d;dy=(dy+rb(delta+1+i*2)+128)%256-128
            cx=anchor[0]+dx-64;cy=anchor[1]+dy-8
            left,top=project(cx),cy;w=project(cx+16)-project(cx);h=16
            sx,sy=left-shift[0],top-shift[1]
            out=np.zeros((h,16),np.uint8)
            for y in range(h):
                for x in range(w):
                    if 0<=sy+y<240 and 0<=sx+x<320 and top+y<192:out[y,x]=letters[letter][sy+y,sx+x]
            if not shadow_variant:
                covered[max(0,top):min(240,top+h),max(0,left):min(320,left+w)]=True
            key=(code<<6)+(cy%6)*6+cx%6
            if key in slices and not np.array_equal(slices[key],out):conflicts.append([hex(code),cx%6,cy%6])
            slices[key]=out
            row=(key,letter,sx,sy,max(0,min(16,192-top)))
            if row not in records:records.append(row)
    missing=int(np.count_nonzero((letters[letter]!=0)&~covered));coverage.append(missing)
assert not conflicts,conflicts
assert not any(coverage),coverage
records=sorted({r[0]:r for r in records}.values())
header='/* Generated by art/frontend/r10_r10/build_title.py. Arcade-raster adaptation. */\n'
header+='#ifndef FRONTEND_R10_NATIVE_TITLE_DATA_H\n#define FRONTEND_R10_NATIVE_TITLE_DATA_H\n#include <stdint.h>\n'
# Each row is cropped independently. offsets[y+1]-offsets[y] gives the packed
# row length, while left[y] gives its X origin relative to the letter anchor.
# The final nibble of an odd-width row is transparent, so width needs no table.
header+='typedef struct {const uint8_t *pixels;const uint16_t *offsets;const uint8_t *left;int16_t x,y;uint8_t height;} frontend_title_bitmap;\n'
descriptors=[]
bitmap_manifest=[]
for i,pixels in enumerate(letters):
    yy,xx=np.where(pixels);x=int(xx.min());y=int(yy.min());height=int(yy.max())-y+1
    raw=bytearray();offsets=[0];left=[];max_width=0
    for row in pixels[y:y+height]:
        nz=np.flatnonzero(row)
        assert len(nz), (i,len(left))
        row_left=int(nz.min());row_right=int(nz.max());row_width=row_right-row_left+1
        assert 0<=row_left-x<=255 and row_width<=255
        values=list(int(v) for v in row[row_left:row_right+1])
        if len(values)&1:values.append(0)
        raw.extend((values[j]<<4)|values[j+1] for j in range(0,len(values),2))
        offsets.append(len(raw));left.append(row_left-x);max_width=max(max_width,row_width)
    header+=f'static const uint8_t frontend_title_{i}_pixels[{len(raw)}]={{\n'
    header+=''.join(' '+','.join(f'0x{v:02x}' for v in raw[j:j+24])+',\n' for j in range(0,len(raw),24))+'};\n'
    header+=f'static const uint16_t frontend_title_{i}_offsets[{len(offsets)}]={{\n'
    header+=''.join(' '+','.join(str(v) for v in offsets[j:j+16])+',\n' for j in range(0,len(offsets),16))+'};\n'
    header+=f'static const uint8_t frontend_title_{i}_left[{len(left)}]={{\n'
    header+=''.join(' '+','.join(str(v) for v in left[j:j+24])+',\n' for j in range(0,len(left),24))+'};\n'
    descriptors.append((i,x,y,height))
    bitmap_manifest.append(dict(name=source['letters'][i]['name'],x=x,y=y,height=height,pixel_bytes=len(raw),row_metadata_bytes=len(offsets)*2+len(left),max_row_width=max_width))
header+='static const frontend_title_bitmap frontend_title_bitmaps[4]={\n'
header+=''.join(' {frontend_title_%d_pixels,frontend_title_%d_offsets,frontend_title_%d_left,%d,%d,%d},\n'%(i,i,i,x,y,h) for i,x,y,h in descriptors)+'};\n'
header+='typedef struct {uint32_t key;int16_t x,y;uint8_t letter,clip_height;} frontend_title_slice;\n'
header+='static const frontend_title_slice frontend_title_slices[]={\n'
header+=''.join(' {%du,%d,%d,%d,%d},\n'%(key,x,y,letter,clip) for key,letter,x,y,clip in records)+'};\n#endif\n'
(ROOT/'frontend/title_native_data.h').write_text(header)
# Canonical preview (RGB444 expanded to 8-bit): shadow first, then main art.
preview=np.zeros((240,320,3),np.uint8);preview[:]=[0,0,153]
union=np.zeros((240,320),bool)
for p in letters:union|=p!=0
shadow_mask=np.zeros_like(union);shadow_mask[8:,13:]=union[:-8,:-13]
# The production title field is deliberately clipped to y112..191.
shadow_mask[192:]=False
preview[shadow_mask]=[17,17,68]
for i,pixels in enumerate(letters):
    for pen in range(1,11):preview[pixels==pen]=[c*17 for c in rgb444(palettes[i][pen-1])]
Image.fromarray(preview).save(HERE/'pang_native_preview.png')
manifest=dict(native_resolution=[320,240],horizontal_projection='floor(5*x/6)',vertical_projection='1:1',resampling=False,
 source_image='../r10_r14/pang_arcade_adapted.png',letter_pixels=[int(np.count_nonzero(p)) for p in letters],
 letter_bitmaps=bitmap_manifest,
 source_sha256=hashlib.sha256((HERE.parent/'r10_r14/pang_arcade_adapted.png').read_bytes()).hexdigest(),
 bank3_sha256=hashlib.sha256(bank).hexdigest(),cells=len(records),outside_original_animation_cell_coverage=coverage,
 moving_and_settled_share_pixels=True,header_sha256=hashlib.sha256(header.encode()).hexdigest())
(HERE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(json.dumps(manifest,indent=2))
