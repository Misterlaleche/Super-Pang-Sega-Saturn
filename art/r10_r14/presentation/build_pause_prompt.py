#!/usr/bin/env python3
"""Compile the retained 64x16 FNT4-style PAUSED plaque to a 4bpp VDP1 asset."""
from pathlib import Path
from PIL import Image
import hashlib,json
HERE=Path(__file__).resolve().parent
image=Image.open(HERE/'pause_prompt.png').convert('RGBA')
assert image.size==(64,16)
# Transparent first; remaining colors retain their exact RGB444 identities.
colors=[(0,0,0,0),(0,0,0,255),(17,17,119,255),(17,102,221,255),
        (255,255,0,255),(170,221,255,255),(17,170,255,255),(255,255,255,255)]
index={c:i for i,c in enumerate(colors)}
rgba=list(image.getdata())
unknown=sorted(set(rgba)-set(colors));assert not unknown,unknown
pens=[index[p] for p in rgba]
raw=bytes((pens[i]<<4)|pens[i+1] for i in range(0,len(pens),2))
def rgb555(c):
    if c[3]==0:return 0
    r,g,b=[round(v/17) for v in c[:3]]
    r5=r*2+(r>>3);g5=g*2+(g>>3);b5=b*2+(b>>3)
    return 0x8000|r5|(g5<<5)|(b5<<10)
clut=[rgb555(c) for c in colors]+[0]*8
h='''/* Generated by art/r10_r14/presentation/build_pause_prompt.py.\n * Original FNT4-style glyphs on a stable native64x16 bevel plaque. */\n#ifndef R14_PAUSE_PROMPT_H\n#define R14_PAUSE_PROMPT_H\n#include <stdint.h>\n#define R14_PAUSE_PROMPT_WIDTH 64u\n#define R14_PAUSE_PROMPT_HEIGHT 16u\n'''
h+='static const uint16_t r14_pause_prompt_clut[16]={'+','.join(f'0x{x:04x}' for x in clut)+'};\n'
h+=f'static const uint8_t r14_pause_prompt[{len(raw)}]={{\n'
h+=''.join(' '+','.join(f'0x{x:02x}' for x in raw[i:i+24])+',\n' for i in range(0,len(raw),24))+'};\n#endif\n'
(HERE/'pause_prompt.h').write_text(h)
(HERE/'manifest.json').write_text(json.dumps({
 'resolution':[64,16],'method':'Retained original FNT4-style glyph raster; no geometric font substitution',
 'colors':len(colors),'bytes':len(raw),'png_sha256':hashlib.sha256((HERE/'pause_prompt.png').read_bytes()).hexdigest(),
 'header_sha256':hashlib.sha256(h.encode()).hexdigest()},indent=2)+'\n')
print(f'pause prompt: {len(raw)} bytes, {len(colors)} colors')
