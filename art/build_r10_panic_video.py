#!/usr/bin/env python3
"""Export only original ROM constants used by the native Panic HUD routines."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'c13_reference/fuentes/build/wp00/decoded/data.bin'
EXPECTED = '9d460c57aac71d4ec9e7e8e6d361e259ff789fd7aeee7f545a60c688c63a09f2'


def main():
    data = SOURCE.read_bytes()
    assert hashlib.sha256(data).hexdigest() == EXPECTED
    snippets = []

    def get(name, bank, address, size):
        start = address if bank < 0 else 0x10000 + bank * 0x4000 + address - 0x8000
        values = data[start:start + size]
        assert len(values) == size
        snippets.append(dict(name=name, bank=bank, address=address, bytes=size,
                             sha256=hashlib.sha256(values).hexdigest()))
        return values

    arrays = [
        ('panic_actor_palette', get('BANK13:800C Panic initial actor palette', 13, 0x800c, 512)),
        ('panic_digits', get('FIXED152E digit glyph words', -1, 0x152e, 20)),
        ('panic_label', get('BANK5:8474 LEVEL glyph low bytes', 5, 0x8474, 10)),
        ('panic_gauge', get('BANK13:8F8C empty and filled gauge palettes', 13, 0x8f8c, 768)),
        ('panic_flash_palette', get('BANK13:8CEC palette phases', 13, 0x8cec, 96)),
        ('panic_ready_palette', get('BANK12:80E8 READY palette variants', 12, 0x80e8, 96)),
        ('panic_ready_selector', get('FIXED1F9E Tour-phase palette selector', -1, 0x1f9e, 40)),
        ('panic_flash_pointer', get('FIXED1F96 Panic flash pointers', -1, 0x1f96, 8)),
    ]
    out = ['/* Generated by art/build_r10_panic_video.py from original ROM DATA. */',
           '#ifndef SPANG_PANIC_VIDEO_DATA_H', '#define SPANG_PANIC_VIDEO_DATA_H']
    for name, values in arrays:
        out.append('static const uint8_t %s[%d] = {' % (name, len(values)))
        out.extend(' ' + ','.join('0x%02x' % v for v in values[i:i + 16]) + ','
                   for i in range(0, len(values), 16))
        out.append('};')
    out += ['#endif', '']
    (ROOT / 'stage/spang_panic_video_data.h').write_text('\n'.join(out))
    report = dict(source=str(SOURCE), source_sha256=EXPECTED, snippets=snippets,
                  total_rom_bytes=sum(len(v) for _, v in arrays),
                  runtime='Native C drawing and palette routines; no captured frame playback')
    (ROOT / 'verification/r10/art/panic_video_sources.json').write_text(json.dumps(report, indent=2) + '\n')
    print('Exported', report['total_rom_bytes'], 'original Panic video constant bytes')


if __name__ == '__main__':
    main()
