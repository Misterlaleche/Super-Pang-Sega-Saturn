"""Make an unscaled attract prompt from the retained original8px font.

Only palette semantics change: blue matte becomes transparent, outline stays
black, and glyph shading becomes white for contrast on all scene backgrounds.
No source column/row is removed or interpolated.
"""
from pathlib import Path
import hashlib,json,zlib
from PIL import Image

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
TEXT='PRESS START BUTTON'

def main():
 b=(ROOT/'cd/ART/CHARDF.BIN').read_bytes();m=(ROOT/'cd/ART/CHARMDF.BIN').read_bytes()
 blocks={};pixels=[]
 for ch in TEXT:
  o=int.from_bytes(m[8+ord(ch)*2:10+ord(ch)*2],'big')*32;n=o//4096
  if n not in blocks:
   lo=int.from_bytes(b[8+n*4:12+n*4],'big');hi=int.from_bytes(b[12+n*4:16+n*4],'big')
   blocks[n]=zlib.decompress(b[lo+4:hi],-15)
  raw=blocks[n][o%4096:o%4096+32]
  assert len(raw)==32
  pixels.append([0 if p in (11,15) else 1 if p==10 else 2 for v in raw for p in (v>>4,v&15)])
 width=len(TEXT)*8;packed=bytearray();image=Image.new('RGBA',(width,8))
 for y in range(8):
  row=[p[y*8+x] for p in pixels for x in range(8)]
  for x in range(0,width,2):packed.append((row[x]<<4)|row[x+1])
  for x,pen in enumerate(row):image.putpixel((x,y),((0,0,0,0),(0,0,0,255),(255,255,255,255))[pen])
 out=HERE/'presentation';out.mkdir(exist_ok=True)
 lines=['/* Generated by art/r10_r10/build_start_prompt.py. Native8px glyphs. */',
  '#ifndef R10_START_PROMPT_H','#define R10_START_PROMPT_H','#include <stdint.h>',
  f'#define R10_START_PROMPT_WIDTH {width}u',
  'static const uint16_t r10_start_prompt_clut[16]={0,0x8000,0xffff};',
  f'static const uint8_t r10_start_prompt[{len(packed)}]={{']
 lines += [' '+','.join('0x%02x'%v for v in packed[i:i+16])+',' for i in range(0,len(packed),16)]
 (out/'start_prompt.h').write_text('\n'.join(lines+['};','#endif','']))
 image.save(out/'start_prompt.png')
 (out/'manifest.json').write_text(json.dumps({'text':TEXT,'size':[width,8],'font':'unchanged original8x8 glyph geometry','sha256':hashlib.sha256(packed).hexdigest()},indent=2)+'\n')

if __name__=='__main__':main()
